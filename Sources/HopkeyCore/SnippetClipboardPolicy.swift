import Foundation

/// Служебные pasteboard-типы соглашения nspasteboard.org. Менеджеры буфера (и наша же
/// история) не записывают копии с этими пометками.
public enum PasteboardMarker {
    /// Значение секретное: не показывать и не хранить (пароль-менеджеры ставят его на пароли).
    public static let concealed = "org.nspasteboard.ConcealedType"
    /// Запись временная, её скоро заменят/восстановят: в историю не нужна.
    public static let transient = "org.nspasteboard.TransientType"
    /// Значение сгенерировано программой, а не скопировано пользователем.
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    /// Пометки, при которых копию не пишем в историю буфера.
    public static let skipHistory: Set<String> = [concealed, transient, autoGenerated]

    /// Есть ли среди типов текущей копии пометка «не записывать».
    public static func shouldSkipHistory(types: [String]) -> Bool {
        types.contains { skipHistory.contains($0) }
    }
}

/// Как Hopkey кладёт значение сниппета в общий буфер обмена.
///
/// Вставка (`paste`) держит значение в буфере доли секунды и затем восстанавливает прежнее
/// содержимое — такая запись всегда временная и не должна уходить на другие устройства.
/// Копирование (`copy`) оставляет значение в буфере: секрет помечаем скрытым, не отдаём в
/// Universal Clipboard и стираем вскоре после первой вставки (`clearAfterFirstRead`) — или по
/// запасному таймеру `autoClearAfter`, если вставки так и не было.
public struct SnippetClipboardPolicy: Equatable {
    /// Pasteboard-типы-пометки, которые кладутся рядом со строкой.
    public let markers: [String]
    /// Только этот Mac: не передавать запись через Universal Clipboard.
    public let currentHostOnly: Bool
    /// Запасной таймер: через сколько секунд очистить буфер, даже если вставки не было
    /// (nil — не очищать).
    public let autoClearAfter: TimeInterval?
    /// Через сколько секунд после первого чтения значения (то есть вставки) очистить буфер
    /// (nil — не следить за вставкой). Пауза нужна: часть приложений читает буфер дважды за одну
    /// вставку.
    public let clearAfterFirstRead: TimeInterval?

    public init(markers: [String], currentHostOnly: Bool, autoClearAfter: TimeInterval?,
                clearAfterFirstRead: TimeInterval? = nil) {
        self.markers = markers
        self.currentHostOnly = currentHostOnly
        self.autoClearAfter = autoClearAfter
        self.clearAfterFirstRead = clearAfterFirstRead
    }

    /// Запасной срок жизни секретного сниппета в буфере, если его так и не вставили.
    public static let defaultSecretLifetime: TimeInterval = 30
    /// Пауза между первой вставкой секрета и очисткой буфера.
    public static let firstReadGrace: TimeInterval = 1

    /// Вставка: значение в буфере лишь до восстановления прежнего содержимого.
    public static func paste(kind: SnippetKind) -> SnippetClipboardPolicy {
        SnippetClipboardPolicy(
            markers: kind.isSecret
                ? [PasteboardMarker.concealed, PasteboardMarker.transient]
                : [PasteboardMarker.transient],
            currentHostOnly: true,
            autoClearAfter: nil
        )
    }

    /// Копирование: значение остаётся в буфере для ручного ⌘V. Несекретные сниппеты (ссылки,
    /// шаблонные ответы) — обычная копия: пользователь может захотеть их и на другом устройстве.
    public static func copy(kind: SnippetKind,
                            secretLifetime: TimeInterval = defaultSecretLifetime) -> SnippetClipboardPolicy {
        guard kind.isSecret else {
            return SnippetClipboardPolicy(markers: [], currentHostOnly: false, autoClearAfter: nil)
        }
        return SnippetClipboardPolicy(
            markers: [PasteboardMarker.concealed],
            currentHostOnly: true,
            autoClearAfter: secretLifetime > 0 ? secretLifetime : nil,
            clearAfterFirstRead: firstReadGrace
        )
    }
}

/// Решение об автоочистке буфера: стираем, только если в буфере всё ещё наша запись.
/// `changeCount` растёт при каждой записи в буфер — если он изменился, пользователь (или
/// другое приложение) уже положил туда что-то своё, и трогать это нельзя.
public enum ClipboardAutoClear {
    public static func shouldClear(writtenChangeCount: Int, currentChangeCount: Int) -> Bool {
        writtenChangeCount == currentChangeCount
    }
}
