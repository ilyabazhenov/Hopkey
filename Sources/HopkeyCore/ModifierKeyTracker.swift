import Foundation

/// Определяет «нажат/отпущен» для конкретной модификаторной клавиши по событиям `.flagsChanged`.
///
/// Тонкость: левый и правый варианты модификатора (⌘/⇧/⌥/⌃) делят ОДИН бит флага, но у них
/// разные keyCode. Поэтому направление (down/up) нельзя брать из бита флага: когда зажат парный
/// модификатор, бит остаётся выставленным и после отпускания второго. Ведём состояние по keyCode:
/// каждое событие для данного keyCode переключает его между «нажат» и «отпущен». Бит используем
/// только как страховку: если он сброшен — обе клавиши точно отпущены.
///
/// Чистый тип без AppKit — под юнит-тестами (сам маппинг keyCode→бит живёт в мониторе).
public final class ModifierKeyTracker {

    private var down: Set<Int> = []

    public init() {}

    public func reset() { down.removeAll() }

    /// Обновляет состояние клавиши и возвращает, стало ли это событие нажатием (`true`) или
    /// отпусканием (`false`). `bitSet` — выставлен ли сейчас общий флаг этого модификатора.
    public func update(keyCode: Int, bitSet: Bool) -> Bool {
        guard bitSet else {
            // Флаг сброшен → обе (левая и правая) клавиши точно отпущены.
            down.remove(keyCode)
            return false
        }
        // Флаг выставлен: этот keyCode либо только что нажат, либо отпущен при зажатом парном.
        // Первое событие для keyCode — нажатие, следующее — отпускание.
        if down.contains(keyCode) {
            down.remove(keyCode)
            return false
        }
        down.insert(keyCode)
        return true
    }
}
