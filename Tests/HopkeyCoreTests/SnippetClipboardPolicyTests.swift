import XCTest
@testable import HopkeyCore

final class SnippetClipboardPolicyTests: XCTestCase {

    // MARK: paste

    func testPasteSecretIsConcealedTransientAndLocal() {
        let p = SnippetClipboardPolicy.paste(kind: .secret)
        XCTAssertEqual(Set(p.markers), [PasteboardMarker.concealed, PasteboardMarker.transient])
        XCTAssertTrue(p.currentHostOnly)
        XCTAssertNil(p.autoClearAfter)  // прежнее содержимое восстанавливается само
        XCTAssertNil(p.clearAfterFirstRead)
    }

    func testPasteNonSecretIsTransientButNotConcealed() {
        for kind in [SnippetKind.text, .link] {
            let p = SnippetClipboardPolicy.paste(kind: kind)
            XCTAssertEqual(p.markers, [PasteboardMarker.transient], "\(kind)")
            XCTAssertTrue(p.currentHostOnly, "\(kind)")
            XCTAssertNil(p.autoClearAfter, "\(kind)")
            XCTAssertNil(p.clearAfterFirstRead, "\(kind)")
        }
    }

    func testEveryPasteIsSkippedByHistory() {
        for kind in SnippetKind.allCases {
            XCTAssertTrue(PasteboardMarker.shouldSkipHistory(types: SnippetClipboardPolicy.paste(kind: kind).markers))
        }
    }

    // MARK: copy

    func testCopySecretIsConcealedLocalAndAutoCleared() {
        let p = SnippetClipboardPolicy.copy(kind: .secret)
        XCTAssertEqual(p.markers, [PasteboardMarker.concealed])
        XCTAssertTrue(p.currentHostOnly)
        XCTAssertEqual(p.autoClearAfter, 30)
    }

    func testCopySecretIsClearedSoonAfterFirstPaste() {
        let p = SnippetClipboardPolicy.copy(kind: .secret)
        XCTAssertEqual(p.clearAfterFirstRead, SnippetClipboardPolicy.firstReadGrace)
        // очистка после вставки должна наступать раньше запасного таймера
        XCTAssertLessThan(p.clearAfterFirstRead!, p.autoClearAfter!)
    }

    func testCopySecretUsesCustomLifetime() {
        XCTAssertEqual(SnippetClipboardPolicy.copy(kind: .secret, secretLifetime: 45).autoClearAfter, 45)
    }

    func testCopySecretWithZeroLifetimeHasNoBackstopButStillClearsAfterPaste() {
        let p = SnippetClipboardPolicy.copy(kind: .secret, secretLifetime: 0)
        XCTAssertNil(p.autoClearAfter)
        XCTAssertEqual(p.clearAfterFirstRead, SnippetClipboardPolicy.firstReadGrace)
    }

    func testCopyNonSecretIsPlainCopy() {
        for kind in [SnippetKind.text, .link] {
            let p = SnippetClipboardPolicy.copy(kind: kind)
            XCTAssertTrue(p.markers.isEmpty, "\(kind)")
            XCTAssertFalse(p.currentHostOnly, "\(kind)")
            XCTAssertNil(p.autoClearAfter, "\(kind)")
            XCTAssertNil(p.clearAfterFirstRead, "\(kind)")
        }
    }

    // MARK: PasteboardMarker

    func testSkipHistoryRecognisesAllMarkers() {
        XCTAssertTrue(PasteboardMarker.shouldSkipHistory(types: ["public.utf8-plain-text", PasteboardMarker.concealed]))
        XCTAssertTrue(PasteboardMarker.shouldSkipHistory(types: [PasteboardMarker.transient]))
        XCTAssertTrue(PasteboardMarker.shouldSkipHistory(types: [PasteboardMarker.autoGenerated]))
    }

    func testPlainCopyIsRecorded() {
        XCTAssertFalse(PasteboardMarker.shouldSkipHistory(types: ["public.utf8-plain-text"]))
        XCTAssertFalse(PasteboardMarker.shouldSkipHistory(types: []))
    }

    // MARK: ClipboardAutoClear

    func testClearsWhenClipboardUntouched() {
        XCTAssertTrue(ClipboardAutoClear.shouldClear(writtenChangeCount: 42, currentChangeCount: 42))
    }

    func testKeepsWhenSomethingWasCopiedSince() {
        XCTAssertFalse(ClipboardAutoClear.shouldClear(writtenChangeCount: 42, currentChangeCount: 43))
    }
}
